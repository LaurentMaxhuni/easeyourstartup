// Regenerates src/lib/design-studio/font-metrics.ts: per-character advance
// widths (printable ASCII, in ems) for every design font at weights 400/800.
// Usage: DESIGN_CHROMIUM_EXECUTABLE_PATH=<chromium or edge> node scripts/measure-design-fonts.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { chromium } from "playwright-core";

const executablePath = process.env.DESIGN_CHROMIUM_EXECUTABLE_PATH;
if (!executablePath) throw new Error("Set DESIGN_CHROMIUM_EXECUTABLE_PATH.");
const root = process.cwd();
const fontDir = path.join(root, "public", "design-fonts");
const catalog = readFileSync(path.join(root, "src", "lib", "design-studio", "fonts.ts"), "utf8");
// Family/slug pairs come from the catalog's variable()/fixed() declarations.
const families = [...catalog.matchAll(/(?:variable|fixed)\("([^"]+)", "([^"]+)"/g)].map(([, family, slug]) => ({ family, slug }));
const face = (family, file, weight, style) => `@font-face{font-family:"${family}";src:url(data:font/woff2;base64,${readFileSync(file).toString("base64")});font-weight:${weight};font-style:${style}}`;
let css = ["outfit-latin.woff2"].map((file) => face("Outfit", path.join(root, "src", "app", "fonts", file), "100 900", "normal")).join("");
for (const { family, slug } of families) {
  for (const file of readdirSync(fontDir).filter((name) => name.startsWith(`${slug}-latin-`) && !name.includes("-latin-ext-") && name.endsWith("-normal.woff2"))) {
    const weight = /-latin-(wght|\d+)-/.exec(file)[1];
    css += face(family, path.join(fontDir, file), weight === "wght" ? "100 1000" : weight, "normal");
  }
}
const names = ["Outfit", ...families.map(({ family }) => family), "Arial", "Georgia", "Verdana", "Courier New"];
const browser = await chromium.launch({ executablePath });
try {
  const page = await browser.newPage();
  await page.setContent(`<style>${css}</style>`);
  const metrics = await page.evaluate(async (names) => {
    const context = document.createElement("canvas").getContext("2d");
    const result = {};
    for (const name of names) {
      result[name] = [];
      for (const weight of [400, 800]) {
        await document.fonts.load(`${weight} 1000px "${name}"`);
        context.font = `${weight} 1000px "${name}"`;
        const widths = [];
        for (let code = 32; code < 127; code++) widths.push(Math.round(context.measureText(String.fromCharCode(code)).width) / 1000);
        result[name].push(widths);
      }
    }
    return result;
  }, names);
  const lines = Object.entries(metrics).map(([name, [regular, heavy]]) => `  ${JSON.stringify(name)}: [${JSON.stringify(regular)}, ${JSON.stringify(heavy)}],`);
  writeFileSync(path.join(root, "src", "lib", "design-studio", "font-metrics.ts"), `// Generated by scripts/measure-design-fonts.mjs. Do not edit by hand.
// Advance widths in ems for characters U+0020-U+007E at weights 400 and 800.
import type { DesignFontFamily } from "./fonts";

export const FONT_ADVANCES: Record<DesignFontFamily, [number[], number[]]> = {
${lines.join("\n")}
};
`);
} finally {
  await browser.close();
}
